            NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT CONNECTION LIMIT 10;
    ELSE
        ALTER ROLE admin_datos WITH LOGIN PASSWORD 'AdminDatos_FoodStore_2026!'
            NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT CONNECTION LIMIT 10;
