CREATE OR REPLACE FUNCTION public.fn_autenticar(
    p_email    VARCHAR,
    p_password TEXT
)
RETURNS TABLE (
    autenticado BOOLEAN,
    usuario_id  BIGINT,
    rol_usuario VARCHAR(40),
    mensaje     TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_id            BIGINT;
    v_hash_guardado TEXT;
    v_rol           VARCHAR(40);
    v_hash_input    TEXT;
BEGIN
    v_hash_input := encode(digest(p_password, 'sha256'), 'hex');

    SELECT u.id, u.password_hash, u.rol
    INTO v_id, v_hash_guardado, v_rol
    FROM public.usuario u
    WHERE lower(u.email) = lower(trim(p_email));

    IF NOT FOUND OR v_hash_guardado <> v_hash_input THEN
        RAISE WARNING 'AUTH_FAIL: intento de inicio de sesion fallido para email=% (invocado por session_user=%, current_user=%)',
            p_email, session_user, current_user;
        RETURN QUERY SELECT FALSE, NULL::BIGINT, NULL::VARCHAR(40), 'Credenciales invalidas'::TEXT;
        RETURN;
    END IF;

    RAISE NOTICE 'AUTH_OK: inicio de sesion exitoso para email=% (usuario_id=%, rol=%, session_user=%)',
        p_email, v_id, v_rol, session_user;
    RETURN QUERY SELECT TRUE, v_id, v_rol, 'Autenticacion exitosa'::TEXT;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_resetear_password(
    p_usuario_id     BIGINT,
    p_nueva_password TEXT
)
RETURNS BOOLEAN
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_email VARCHAR(150);
BEGIN
    IF p_nueva_password IS NULL OR length(trim(p_nueva_password)) < 10 THEN
        RAISE EXCEPTION 'La nueva contrasena debe tener al menos 10 caracteres';
    END IF;

    UPDATE public.usuario
    SET password_hash = encode(digest(p_nueva_password, 'sha256'), 'hex')
    WHERE id = p_usuario_id
    RETURNING email INTO v_email;

    IF NOT FOUND THEN
        RAISE WARNING 'RESET_FAIL: usuario_id=% inexistente solicitado por %', p_usuario_id, current_user;
        RETURN FALSE;
    END IF;

    RAISE NOTICE 'RESET_OK: password actualizado para usuario_id=% (email=%) ejecutado por session_user=%, current_user=%',
        p_usuario_id, v_email, session_user, current_user;
    RETURN TRUE;
END;
$$;

