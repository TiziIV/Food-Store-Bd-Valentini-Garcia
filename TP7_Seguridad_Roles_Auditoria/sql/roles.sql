SELECT
    grantee,
    table_name,
    column_name,
    privilege_type
FROM information_schema.column_privileges
WHERE table_schema = 'public'
  AND table_name IN ('usuario', 'producto', 'cliente')
  AND grantee IN ('rol_app_lectura', 'rol_soporte', 'rol_logistica', 'rol_auditor')
ORDER BY grantee, table_name, column_name, privilege_type;

