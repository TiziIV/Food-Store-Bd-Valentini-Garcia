        CREATE ROLE rol_logistica NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rol_auditor') THEN
        CREATE ROLE rol_auditor NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT;
    END IF;

    -- Roles de login (Clase 1)
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'app_web') THEN
        CREATE ROLE app_web LOGIN PASSWORD 'AppWeb_FoodStore_2026!'
            NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT CONNECTION LIMIT 50;
