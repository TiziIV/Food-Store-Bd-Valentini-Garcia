GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public TO admin_datos;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA public TO admin_datos;
GRANT EXECUTE ON ALL PROCEDURES IN SCHEMA public TO admin_datos;

